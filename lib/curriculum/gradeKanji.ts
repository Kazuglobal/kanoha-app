/**
 * 漢字の問題の自動生成に使う、1・2年で習う漢字の語と読み(ひらがな)。
 * - 読みが 1 つにきまる語だけを入れる(「日」「上」「生」など 読みが多い漢字は入れない)
 * - 読みは どの語も ちがう(読みから漢字をえらぶ問題で、答えが 1 つにきまるように)
 * - single = 漢字 1 字だけの語、compound = 熟語・送りがなつきの語
 * 読みの正しさは、人の目での確認が必要(tests/curriculum/gradeKanji.test.ts は形の決まりだけを見る)。
 */

export type KanjiGrade = 1 | 2;
export type KanjiKind = "single" | "compound";

export interface KanjiWord {
  readonly word: string;
  readonly reading: string;
  readonly grade: KanjiGrade;
  readonly kind: KanjiKind;
}

const entry = (grade: KanjiGrade, kind: KanjiKind, word: string, reading: string): KanjiWord => ({ grade, kind, word, reading });
const g1s = (word: string, reading: string) => entry(1, "single", word, reading);
const g1c = (word: string, reading: string) => entry(1, "compound", word, reading);
const g2s = (word: string, reading: string) => entry(2, "single", word, reading);
const g2c = (word: string, reading: string) => entry(2, "compound", word, reading);

